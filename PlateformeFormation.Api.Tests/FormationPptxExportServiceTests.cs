    // The reported bug: the évaluation slide's loop `break`'d out the moment one item's real measured
    // height didn't fit the remaining space, silently dropping every item after it — 5 évaluation
    // entries in evaluation[] could render as only 3 bars with no indication 2 were missing. The fix
    // paginates onto additional slides instead, so every item must appear somewhere in the deck.
    [Fact]
    public void GeneratePptx_EvaluationSlidesRepresentEveryItemEvenWhenTheyDontFitOnOnePage()
    {
        var noms = new[]
        {
            "Évaluation continue – Suivi des exercices formatifs tout au long du parcours",
            "Évaluation finale – Projet de synthèse noté par un jury externe",
            "Quiz de mi-parcours sur les fondamentaux théoriques",
            "Projet final",
            "Participation et engagement",
        };
        var items = string.Join(",", noms.Select((n, i) =>
            $"{{\"nom\":\"{n}\",\"pct\":{(i + 1) * 15},\"estEvaluationContinue\":{(i % 2 == 0 ? "true" : "false")}}}"));

        var formation = new Formation
        {
            Id = 6,
            Titre = "Formation avec cinq modalités d'évaluation",
            CreePar = 1,
            Objectifs = "{}",
            Modules = "[]",
            Activites = "[]",
            MethodesEvaluation = "[" + items + "]",
        };

        var service = new FormationPptxExportService();
        var bytes = service.GeneratePptx(formation);

        using var stream = new MemoryStream(bytes);
        using var doc = PresentationDocument.Open(stream, false);

        var errors = new OpenXmlValidator().Validate(doc).ToList();
        Assert.True(errors.Count == 0, string.Join("\n", errors.Select(e => $"{e.Path?.XPath}: {e.Description}")));
        AssertNoDuplicateShapeIds(doc);

        var allText = doc.PresentationPart!.SlideParts
            .SelectMany(sp => sp.Slide!.Descendants<DocumentFormat.OpenXml.Drawing.Text>())
            .Select(t => t.Text)
            .ToList();

        foreach (var nom in noms)
        {
            // Truncate() may shorten a long name to fit its box — check a stable prefix rather than
            // the full string, which is exactly what would go missing if pagination regressed back to
            // a silent break.
            var prefix = nom.Length > 15 ? nom[..15] : nom;
            Assert.Contains(allText, t => t.StartsWith(prefix, StringComparison.Ordinal));
        }
    }

    // Regression for a real bug found in review: the Sommaire slide rendered every top-level section
    // on one fixed-height slide with no pagination and an unscaled 30pt numero glyph, unlike every
    // sibling list slide in this deck (Vue d'ensemble, Objectifs pédagogiques...) which paginates at 5
    // rows/page. A formation with every optional section present (Contexte, Objectifs, Bénéfices, Vue
    // d'ensemble, Modules, Test de positionnement, Évaluation, Ressources — 8 rows) used to cram all 8
    // onto one slide. This also verifies the Sommaire's own page count is correctly folded into the
    // slide numbers it prints for every later section — a formation this rich pushes the Sommaire
    // itself onto 2 pages, which shifts every subsequent slide number by one extra page.
    [Fact]
    public void GeneratePptx_SommaireWithEverySectionPresentPaginatesAndSlideNumbersStayAccurate()
    {
        var formation = new Formation
        {
            Id = 7,
            Titre = "Formation complète avec toutes les sections optionnelles",
            CreePar = 1,
            Objectifs = """
                {
                  "contexte": "Cette formation répond à un besoin identifié de montée en compétence sur les pratiques DevOps modernes",
                  "publicCible": "Développeurs",
                  "beneficesEntreprise": [{"titre": "Livraisons plus fréquentes", "justification": "Moins de régressions en production."}],
                  "ressourcesPedagogiques": ["Documentation officielle Jenkins"],
                  "testPositionnement": {"objectif": "Évaluer le niveau Git", "seuilParcoursStandardPct": 70}
                }
                """,
            DureeEstimee = 6,
            Modules = """
                [
                  {"numero":1,"titre":"Introduction à la culture DevOps","dureeHeures":3,"objectif":"Être capable de décrire les principes de base"},
                  {"numero":2,"titre":"Intégration continue avec Jenkins","dureeHeures":3,"objectif":"Savoir configurer un serveur Jenkins"}
                ]
                """,
            Activites = "[]",
            MethodesEvaluation = """[{"nom":"Évaluation continue","pct":100,"estEvaluationContinue":true}]""",
        };

        var service = new FormationPptxExportService();
        var bytes = service.GeneratePptx(formation);

        using var stream = new MemoryStream(bytes);
        using var doc = PresentationDocument.Open(stream, false);

        var errors = new OpenXmlValidator().Validate(doc).ToList();
        Assert.True(errors.Count == 0, string.Join("\n", errors.Select(e => $"{e.Path?.XPath}: {e.Description}")));
        AssertNoDuplicateShapeIds(doc);

        var slidesInOrder = GetSlidesInOrder(doc);

        // 8 sections / 5 per page = 2 Sommaire pages — title(1) + sommaire(2) precede everything else.
        var sommaireHeadingCount = slidesInOrder.Count(s => SlideHeadingText(s) == "Sommaire");
        Assert.Equal(2, sommaireHeadingCount);

        // For every section whose slide carries its own heading text (everything except the module
        // block, which uses a different per-module layout), the Sommaire's printed slide number must
        // match where that section's slide actually landed in the deck.
        var sectionHeadings = new[]
        {
            "Contexte et enjeux", "Objectifs pédagogiques", "Bénéfices pour l'entreprise",
            "Vue d'ensemble du programme", "Test de positionnement et différenciation",
            "Modalités d'évaluation", "Ressources et pratique",
        };
        var sommaireRows = slidesInOrder
            .Where(s => SlideHeadingText(s) == "Sommaire")
            .SelectMany(s => SommaireRows(s))
            .ToDictionary(r => r.Label, r => r.SlideNumber);

        foreach (var heading in sectionHeadings)
        {
            var actualSlideIndex = slidesInOrder.FindIndex(s => SlideHeadingText(s) == heading) + 1;
            Assert.True(actualSlideIndex > 0, $"No slide found with heading '{heading}'");
            Assert.True(sommaireRows.TryGetValue(heading, out var printedNumber), $"Sommaire has no row for '{heading}'");
            Assert.Equal(actualSlideIndex, printedNumber);
        }
    }

    // Returns slide parts in true document order (via SlideIdList's relationship ids) rather than
    // SlideParts' enumeration order, which isn't guaranteed to match insertion order.
    private static List<SlidePart> GetSlidesInOrder(PresentationDocument doc) =>
        doc.PresentationPart!.Presentation!.SlideIdList!.Elements<DocumentFormat.OpenXml.Presentation.SlideId>()
            .Select(id => (SlidePart)doc.PresentationPart!.GetPartById(id.RelationshipId!.Value!))
            .ToList()!;

    // AddPaperHeader/BuildTitleSlideV2 draw the section heading as a standalone text run — the first
    // text on the slide narrow enough to be a heading (module slides don't have one in this shape, by
    // design, since they use a different per-module layout).
    private static string? SlideHeadingText(SlidePart slidePart) =>
        slidePart.Slide!.Descendants<DocumentFormat.OpenXml.Presentation.Shape>()
            .FirstOrDefault(s => s.NonVisualShapeProperties?.NonVisualDrawingProperties?.Name?.Value == "heading")
            ?.TextBody?.Descendants<DocumentFormat.OpenXml.Drawing.Text>().FirstOrDefault()?.Text;

    // Reconstructs (label, printed slide number) rows from a Sommaire slide's own shapes — titreN and
    // pageN share the same row index N.
    private static IEnumerable<(string Label, int SlideNumber)> SommaireRows(SlidePart slidePart)
    {
        var shapes = slidePart.Slide!.Descendants<DocumentFormat.OpenXml.Presentation.Shape>().ToList();
        string? GetTextByName(string name) => shapes
            .FirstOrDefault(s => s.NonVisualShapeProperties?.NonVisualDrawingProperties?.Name?.Value == name)
            ?.TextBody?.Descendants<DocumentFormat.OpenXml.Drawing.Text>().FirstOrDefault()?.Text;

        for (var i = 0; ; i++)
        {
            var label = GetTextByName($"titre{i}");
            if (label is null) yield break;
            var pageText = GetTextByName($"page{i}");
            yield return (label, int.Parse(pageText ?? "0"));
        }
    }

    private static void AssertNoDuplicateShapeIds(PresentationDocument doc)
    {
        foreach (var slidePart in doc.PresentationPart!.SlideParts)
        {
            var ids = slidePart.Slide!.Descendants<DocumentFormat.OpenXml.Presentation.NonVisualDrawingProperties>()
                .Select(p => p.Id?.Value).ToList();
            var duplicates = ids.GroupBy(i => i).Where(g => g.Count() > 1).Select(g => g.Key).ToList();
            Assert.True(duplicates.Count == 0, "Duplicate shape ids on a slide: " + string.Join(", ", duplicates));
        }
    }
