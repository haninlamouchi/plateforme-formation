    [Fact]
    public void GeneratePptx_ReturnsAWellFormedZipContainer()
    {
        var service = new FormationPptxExportService();
        var bytes = service.GeneratePptx(BuildFormation());

        Assert.NotEmpty(bytes);
        // .pptx is an OPC (ZIP) package — "PK\x03\x04" is the local-file-header magic number.
        Assert.Equal((byte)'P', bytes[0]);
        Assert.Equal((byte)'K', bytes[1]);
    }

    // Beyond "it's a ZIP" — reopen the generated bytes and run the OpenXml SDK's own schema
    // validator over every part. This is the strongest check available without PowerPoint installed:
    // a wrong element order or a missing required child would surface here as a validation error,
    // not just silently produce a file PowerPoint refuses to open.
    [Fact]
    public void GeneratePptx_ProducesSchemaValidPresentation()
    {
        var service = new FormationPptxExportService();
        var bytes = service.GeneratePptx(BuildFormation());

        using var stream = new MemoryStream(bytes);
        using var doc = PresentationDocument.Open(stream, false);

        var validator = new OpenXmlValidator();
        var errors = validator.Validate(doc).ToList();

        Assert.True(errors.Count == 0,
            string.Join("\n", errors.Select(e => $"{e.Path?.XPath}: {e.Description}")));

        var slideCount = doc.PresentationPart!.SlideParts.Count();
        // Title(1) + Sommaire(1, sections is non-empty) + Objectifs pédagogiques(1, both modules have
        // "objectif") + Agenda(1) + 2 modules + Évaluation(1) +
        // Ressources et pratique(1, ressourcesPedagogiques present) + Clôture(1, always present) = 9.
        // No Contexte/Bénéfices/Test de positionnement slides — none of that data is in this fixture.
        // No separate day-by-day Schedule slide — dropped from the deck entirely (not part of the
        // spec's slide outline; "Vue d'ensemble" is the module timeline only, exactly what Agenda
        // already is).
        Assert.Equal(9, slideCount);
    }

